def _no_jq_path(tmp_path: Path) -> str:
    bin_dir = tmp_path / "no-jq-path"
    bin_dir.mkdir()
    for tool in ("bash", "cat", "git", "python3", "dirname", "mktemp"):
        real = shutil.which(tool)
        if real:
            (bin_dir / tool).symlink_to(real)
    return str(bin_dir)


def test_denied_when_jq_missing(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PATH", _no_jq_path(tmp_path))
    payload = json.dumps({"tool_name": "mcp__github__create_pull_request", "tool_input": {"base": "main", "body": ""}})
    result = subprocess.run(
        ["bash", str(REPO_ROOT / "hooks" / "check-pr-body-preflight.sh")],
        input=payload,
        capture_output=True,
        text=True,
        timeout=60,
        cwd=str(REPO_ROOT),
    )
    assert result.returncode == 2, f"expected deny (exit 2), got {result.returncode}: stderr={result.stderr!r}"
    parsed = json.loads(result.stderr)
    assert parsed["hookSpecificOutput"]["permissionDecision"] == "deny"
    assert "jq is not available" in parsed["systemMessage"]


