def _git(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True)


def _write(repo: Path, relative: str, content: str = "x\n") -> None:
    path = repo / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _copy(repo: Path, relative: str) -> None:
    _write(repo, relative, (REPO_ROOT / relative).read_text(encoding="utf-8"))


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """A scratch repo with a `main` branch published as `origin/main`
    (what the hook resolves its base branch against), carrying every
    script the preflight it wraps depends on."""
    subprocess.run(["git", "init", "-q", "-b", "main", str(tmp_path)], check=True)
    _git(tmp_path, "config", "user.email", "t@e")
    _git(tmp_path, "config", "user.name", "t")
    for relative in (*_HOOK_FILES, *_PREFLIGHT_FILES):
        _copy(tmp_path, relative)
    _write(tmp_path, "README.md")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-qm", "base")
    # A local `origin` remote so `git merge-base origin/main HEAD` resolves
    # without network access. `set-head` matters: without
    # refs/remotes/origin/HEAD the default-branch fallback resolves to
    # nothing and the hook exits early, passing every no-explicit-base
    # test for the wrong reason.
    _git(tmp_path, "remote", "add", "origin", str(tmp_path))
    _git(tmp_path, "fetch", "-q", "origin")
    _git(tmp_path, "remote", "set-head", "origin", "main")
    _git(tmp_path, "checkout", "-q", "-b", "feature")
    return tmp_path


def _publish(repo: Path) -> None:
    """Push the current feature branch's own commits to origin/main, so a
    later `git merge-base origin/main HEAD` on a *different* branch sees
    them -- used to build a stacked-PR fixture."""
    _git(repo, "checkout", "-q", "main")
    _git(repo, "merge", "-q", "feature")
    _git(repo, "push", "-q", "origin", "main")
    _git(repo, "checkout", "-q", "feature")


def _commit(repo: Path, message: str = "change") -> None:
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", message)


def _run(
    repo: Path, body: str, tool_name: str = "mcp__github__create_pull_request", base: str | None = "main"
) -> subprocess.CompletedProcess[str]:
    tool_input: dict[str, str] = {"body": body}
    if base is not None:
        tool_input["base"] = base
    payload = json.dumps({"tool_name": tool_name, "tool_input": tool_input})
    return subprocess.run(
        ["bash", str(repo / "hooks" / "check-pr-body-preflight.sh")],
        input=payload,
        capture_output=True,
        text=True,
        timeout=60,
        cwd=str(repo),
    )


